import streamlit as st

st.set_page_config(
    page_title="СППР: Кадровая динамика",
    layout="wide"
)

pages = {
    "Навигация": [
        st.Page("start.py", title="Главная"),
        st.Page("pages/dashboard_director.py", title="Панель руководителя"),
        st.Page("pages/dashboard_department.py", title="Сводный мониторинг региона"),
    ]
}

pg = st.navigation(pages)

if pg.title == "Главная":
    st.title("Система поддержки принятия решений: Кадровая динамика педагогов")
    st.markdown("Прототип аналитической платформы для мониторинга кадровой ситуации в школах.")

    col1, col2 = st.columns(2)

    with col1:
        st.info(
            "**Сценарий 1: Руководитель образовательной организации**\n\n"
            "Раздел для директора и завучей конкретной школы:\n"
            "- Выбор своей образовательной организации из списка\n"
            "- Анализ соотношения педагогического стажа и числа предметов\n"
            "- Оценка аудиторной нагрузки по предметным кафедрам\n"
            "- Отслеживание доли ушедших учителей и преподавателей с высокой нагрузкой"
        )

    with col2:
        st.success(
            "**Сценарий 2: Орган управления образованием**\n\n"
            "Раздел для анализа кадровой ситуации на уровне города и округов:\n"
            "- Сравнение школ региона по уровню текучести и средней учебной нагрузке\n"
            "- Анализ доли педагогов высшей квалификационной категории по округам\n"
            "- Фильтрация небольших организаций"
        )
else:
    pg.run()